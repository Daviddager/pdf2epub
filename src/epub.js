// Stage 7: build the EPUB skeleton from chapter markdown + figure crops.
// XHTML 1.1 chapters, styles.css, content.opf (EPUB 3, EPUB 2-compatible),
// toc.ncx + nav.xhtml, mimetype + META-INF/container.xml.
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const xmlEscape = (s) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function parseMarkdown(lines) {
  const blocks = [];
  for (const raw of lines) {
    const line = raw.replace(/\s+$/, '');
    if (!line.trim()) continue;
    let m;
    if ((m = line.match(/^(#{1,4})\s+(.*)$/))) {
      blocks.push({ type: 'h', level: m[1].length, text: m[2].trim() });
    } else if ((m = line.match(/^!\[Figure[^\]]*\]\(\.\.\/figures\/([^)]+)\)\s*$/))) {
      blocks.push({ type: 'fig', file: m[1] });
    } else {
      blocks.push({ type: 'p', text: line.trim() });
    }
  }
  return blocks;
}

const isAttribution = (t) => /^—\s*[^—]{1,40}$/.test(t) && t.length < 46;

function renderXHTML(blocks, docTitle, lang) {
  let headId = 0;
  const body = [];
  for (const b of blocks) {
    if (b.type === 'h') {
      const tag = b.level === 1 ? 'h1' : `h${b.level}`;
      const id = b.level === 1 ? 'title' : `sec-${++headId}`;
      body.push(`<${tag} id="${id}">${xmlEscape(b.text)}</${tag}>`);
    } else if (b.type === 'fig') {
      body.push(`<div class="figure"><img src="images/${b.file}" alt="Illustration"/></div>`);
    } else {
      const cls = isAttribution(b.text) ? ' class="attribution"' : '';
      body.push(`<p${cls}>${xmlEscape(b.text)}</p>`);
    }
  }
  return `<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.1//EN" "http://www.w3.org/TR/xhtml11/DTD/xhtml11.dtd">
<html xmlns="http://www.w3.org/1999/xhtml" xml:lang="${lang}">
<head>
  <meta http-equiv="Content-Type" content="application/xhtml+xml; charset=utf-8"/>
  <title>${xmlEscape(docTitle)}</title>
  <link rel="stylesheet" type="text/css" href="styles.css"/>
</head>
<body>
${body.join('\n')}
</body>
</html>
`;
}

function buildStylesheet(cfg) {
  const css = cfg.epub.css;
  return `/* styles.css — generated by pdf2epub
   E-reader typography: justified text, first-line indents,
   page breaks before chapter titles, fluid illustrations. */

body {
  font-family: Georgia, "Times New Roman", "Droid Serif", serif;
  font-size: 1em;
  line-height: 1.5;
  margin: 0 4%;
  padding: 0;
  text-align: justify;
  text-justify: inter-word;
  hyphens: auto;
  -webkit-hyphens: auto;
  -epub-hyphens: auto;
  orphans: 2;
  widows: 2;
  color: #111;
  background: transparent;
}

/* ---- chapter titles start on a fresh page ---- */
h1 {
  font-size: 1.7em;
  font-weight: bold;
  text-align: center;
  line-height: 1.25;
  margin: 2.5em 0 1.2em 0;
  ${css.headingPageBreak ? 'page-break-before: always;\n  break-before: page;' : ''}
  page-break-after: avoid;
  break-after: avoid;
}

h2 { font-size: 1.3em; font-weight: bold; margin: 1.6em 0 0.6em 0; page-break-after: avoid; break-after: avoid; text-align: left; }
h3 { font-size: 1.1em; font-weight: bold; margin: 1.2em 0 0.4em 0; page-break-after: avoid; break-after: avoid; text-align: left; }
h4 { font-size: 1em; font-weight: bold; margin: 1em 0 0.3em 0; page-break-after: avoid; break-after: avoid; text-align: left; }

/* ---- paragraphs: indented first line, no extra inter-paragraph gap ---- */
p { text-indent: ${css.bodyIndent}; margin: 0; padding: 0; text-align: justify; }

/* no indent immediately after a heading */
h1 + p, h2 + p, h3 + p, h4 + p { text-indent: 0; }

/* epigraph signature lines (e.g. "— CORINDA.") */
p.attribution { text-indent: 0; text-align: right; font-style: italic; margin: 0.6em 0 1em 0; }

/* ---- illustrations and diagrams ---- */
img { max-width: 100%; height: auto; border: none; }

div.figure { text-align: center; margin: 1em 0 1.2em 0; padding: 0; page-break-inside: avoid; break-inside: avoid; }
div.figure img { margin: 0 auto; }
`;
}

function run(outDir, cfg, meta) {
  const chaptersDir = path.join(outDir, 'chapters');
  const figDir = path.join(outDir, 'figures');
  const epubDir = path.join(outDir, 'epub');
  const OEBPS = path.join(epubDir, 'OEBPS');
  const lang = meta.language || cfg.epub.language;

  fs.rmSync(epubDir, { recursive: true, force: true });
  fs.mkdirSync(path.join(OEBPS, 'images'), { recursive: true });
  fs.mkdirSync(path.join(epubDir, 'META-INF'), { recursive: true });

  const problems = [];
  const uuid = crypto.createHash('md5').update(`${meta.title}|${meta.author}`).digest('hex');
  const META = {
    title: meta.title,
    creator: meta.author,
    language: lang,
    publisher: meta.publisher || cfg.epub.publisher || '',
    identifier: `urn:uuid:${uuid.slice(0, 8)}-${uuid.slice(8, 12)}-${uuid.slice(12, 16)}-${uuid.slice(16, 20)}-${uuid.slice(20)}`,
    modified: new Date().toISOString().replace(/\.\d+Z$/, 'Z'),
  };

  const mdFiles = fs.readdirSync(chaptersDir).filter((f) => /^chapter-\d+\.md$/.test(f)).sort();
  if (!mdFiles.length) throw new Error(`no chapter-*.md files in ${chaptersDir}`);
  const chapters = [];
  const usedImages = new Set();

  for (const f of mdFiles) {
    const md = fs.readFileSync(path.join(chaptersDir, f), 'utf8');
    const lines = md.split('\n');
    const titleLine = lines.find((l) => /^# /.test(l));
    if (!titleLine) problems.push(`${f}: no '# ' chapter title`);
    const title = titleLine ? titleLine.replace(/^# /, '').trim() : f;

    for (const m of md.matchAll(/!\[[^\]]*\]\(\.\.\/figures\/([^)]+)\)/g)) {
      const name = m[1];
      if (!fs.existsSync(path.join(figDir, name))) problems.push(`${f}: image missing in figures/ -> ${name}`);
      usedImages.add(name);
    }

    const blocks = parseMarkdown(lines);
    const out = f.replace(/\.md$/, '.xhtml');
    fs.writeFileSync(path.join(OEBPS, out), renderXHTML(blocks, `${META.title} — ${title}`, lang));
    chapters.push({ file: out, title });
  }

  for (const name of usedImages) {
    fs.copyFileSync(path.join(figDir, name), path.join(OEBPS, 'images', name));
  }

  fs.writeFileSync(path.join(OEBPS, 'styles.css'), buildStylesheet(cfg));

  // content.opf
  const mani = [], spine = [];
  const addManifest = (id, href, type, extra = '') => mani.push(`    <item id="${id}" href="${href}" media-type="${type}"${extra}/>`);
  const addSpine = (idref) => spine.push(`    <itemref idref="${idref}" linear="yes"/>`);
  addManifest('css', 'styles.css', 'text/css');
  addManifest('nav', 'nav.xhtml', 'application/xhtml+xml', ' properties="nav"');
  addManifest('ncx', 'toc.ncx', 'application/x-dtbncx+xml');
  addSpine('nav');
  chapters.forEach((c, i) => {
    addManifest(`ch${String(i + 1).padStart(2, '0')}`, c.file, 'application/xhtml+xml');
    addSpine(`ch${String(i + 1).padStart(2, '0')}`);
  });
  let imgNo = 0;
  for (const name of [...usedImages].sort()) {
    addManifest(`img${String(++imgNo).padStart(3, '0')}`, `images/${name}`, 'image/png');
  }
  const publisherLine = META.publisher ? `    <dc:publisher>${xmlEscape(META.publisher)}</dc:publisher>\n` : '';
  const opf = `<?xml version="1.0" encoding="utf-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="bookid" xml:lang="${lang}">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="bookid">${META.identifier}</dc:identifier>
    <dc:title>${xmlEscape(META.title)}</dc:title>
    <dc:creator>${xmlEscape(META.creator)}</dc:creator>
    <dc:language>${META.language}</dc:language>
${publisherLine}    <dc:date>${META.modified.slice(0, 10)}</dc:date>
    <meta property="dcterms:modified">${META.modified}</meta>
  </metadata>
  <manifest>
${mani.join('\n')}
  </manifest>
  <spine toc="ncx">
${spine.join('\n')}
  </spine>
</package>
`;
  fs.writeFileSync(path.join(OEBPS, 'content.opf'), opf);

  // toc.ncx
  let play = 0;
  const navPoints = chapters.map((c) => {
    play += 1;
    return `    <navPoint id="np${play}" playOrder="${play}">
      <navLabel><text>${xmlEscape(c.title)}</text></navLabel>
      <content src="${c.file}"/>
    </navPoint>`;
  });
  const ncx = `<?xml version="1.0" encoding="utf-8"?>
<ncx xmlns="http://www.daisy.org/z3986/2005/ncx/" version="2005-1" xml:lang="${lang}">
  <head>
    <meta name="dtb:uid" content="${META.identifier}"/>
    <meta name="dtb:depth" content="1"/>
    <meta name="dtb:totalPageCount" content="0"/>
    <meta name="dtb:maxPageNumber" content="0"/>
  </head>
  <docTitle><text>${xmlEscape(META.title)}</text></docTitle>
  <docAuthor><text>${xmlEscape(META.creator)}</text></docAuthor>
  <navMap>
${navPoints.join('\n')}
  </navMap>
</ncx>
`;
  fs.writeFileSync(path.join(OEBPS, 'toc.ncx'), ncx);

  // nav.xhtml
  const navItems = chapters.map((c) => `      <li><a href="${c.file}">${xmlEscape(c.title)}</a></li>`);
  const nav = `<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="${lang}">
<head>
  <meta charset="utf-8"/>
  <title>Table of Contents</title>
  <link rel="stylesheet" type="text/css" href="styles.css"/>
</head>
<body>
  <nav epub:type="toc" id="toc">
    <h1>Table of Contents</h1>
    <ol>
${navItems.join('\n')}
    </ol>
  </nav>
</body>
</html>
`;
  fs.writeFileSync(path.join(OEBPS, 'nav.xhtml'), nav);

  // container
  fs.writeFileSync(path.join(epubDir, 'mimetype'), 'application/epub+zip');
  fs.writeFileSync(path.join(epubDir, 'META-INF', 'container.xml'), `<?xml version="1.0" encoding="utf-8"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>
`);

  if (problems.length) {
    const err = new Error(`epub build problems:\n${problems.join('\n')}`);
    err.problems = problems;
    throw err;
  }
  return { chapters: chapters.length, images: usedImages.size, epubDir, meta: META };
}

module.exports = { run, parseMarkdown };

if (require.main === module) {
  // usage: node src/epub.js <outDir> '<json meta>' [configPath]
  const cfg = require('./config').loadConfig(process.argv[4]);
  console.log(JSON.stringify(run(process.argv[2], cfg, JSON.parse(process.argv[3] || '{}')), null, 1));
}
